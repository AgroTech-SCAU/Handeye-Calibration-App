const HANDEYE_LANGUAGE_KEY = 'handeye-language'
const HANDEYE_SUPPORTED_LANGUAGES = ['zh-CN', 'en']

function handeyeDetectSystemLanguage() {
  const language = String(navigator.language || 'en').toLowerCase()
  return language.startsWith('zh') ? 'zh-CN' : 'en'
}

function handeyeLoadLanguage() {
  const saved = localStorage.getItem(HANDEYE_LANGUAGE_KEY)
  return HANDEYE_SUPPORTED_LANGUAGES.includes(saved) ? saved : handeyeDetectSystemLanguage()
}

function handeyeTranslate(language, key, variables = {}) {
  const table = HANDEYE_LOCALES[language] || HANDEYE_LOCALES.en
  const fallback = HANDEYE_LOCALES.en[key] || key
  const value = table[key] || fallback
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => variables[name] ?? `{${name}}`)
}

window.HandEyeI18n = {
  locales: HANDEYE_LOCALES,
  loadLanguage: handeyeLoadLanguage,
  setStoredLanguage(language) {
    if (!HANDEYE_SUPPORTED_LANGUAGES.includes(language)) return
    localStorage.setItem(HANDEYE_LANGUAGE_KEY, language)
  },
  t: handeyeTranslate
}
